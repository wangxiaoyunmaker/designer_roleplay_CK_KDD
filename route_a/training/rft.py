"""Leakage-safe OOF rejection-sampling fine-tuning contracts for Realizer."""

from __future__ import annotations

from collections import Counter, defaultdict
from collections.abc import Iterable, Mapping
import hashlib
import math
from typing import Any

from route_a.data.io import canonical_json_bytes
from route_a.inference.selection import Candidate, candidate_failure
from .splitting import NestedSelectionSplit


class RFTContractError(ValueError):
    pass


def participant_set_sha256(participant_ids: Iterable[str]) -> str:
    ids = tuple(sorted(participant_ids))
    if not ids or len(ids) != len(set(ids)):
        raise RFTContractError("participant set must be nonempty and unique")
    return hashlib.sha256(canonical_json_bytes(list(ids))).hexdigest()


def validate_oof_candidate(
    row: Mapping[str, Any],
    split: NestedSelectionSplit,
) -> None:
    required = {
        "participant_id", "record_id", "question_id", "candidate_index",
        "candidate_text", "gold_text", "state_context", "clean_status",
        "source_model_role", "generator_fit_mode", "held_out_fold",
        "generator_train_participants_sha256",
        "generator_checkpoint_manifest_sha256", "bge_similarity", "consistency",
        "forced_stop", "q7_gold_used",
    }
    optional_scoring = {"chrf", "failure_penalty", "failure_reasons", "reward", "reward_pool"}
    if not required <= set(row) or set(row) - required - optional_scoring:
        raise RFTContractError(
            f"RFT candidate fields mismatch; missing={sorted(required-set(row))}, "
            f"extra={sorted(set(row)-required-optional_scoring)}"
        )
    participant = row["participant_id"]
    if row["question_id"] not in {f"Q{i}" for i in range(1, 7)}:
        raise RFTContractError("RFT may use Q1-Q6 only")
    if row["clean_status"] not in {"KEEP", "EDITED"}:
        raise RFTContractError("RFT may use KEEP/EDITED clean text only")
    if row["q7_gold_used"] is not False:
        raise RFTContractError("RFT candidate generation must not use Q7 gold")
    if not isinstance(row["candidate_index"], int) or isinstance(row["candidate_index"], bool) or row["candidate_index"] < 0:
        raise RFTContractError("candidate_index must be a nonnegative integer")
    if not isinstance(row["candidate_text"], str) or not isinstance(row["gold_text"], str) or not row["gold_text"].strip():
        raise RFTContractError("RFT candidate/gold text is invalid")
    states = row["state_context"]
    if not isinstance(states, list) or "V" in states:
        raise RFTContractError("structured V is forbidden in RFT state context")
    for key in ("bge_similarity", "consistency"):
        value = row[key]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(float(value)):
            raise RFTContractError(f"{key} must be finite")
    checkpoint_sha = row["generator_checkpoint_manifest_sha256"]
    if not isinstance(checkpoint_sha, str) or len(checkpoint_sha) != 64:
        raise RFTContractError("generator checkpoint SHA is invalid")
    if participant in split.development_fold:
        expected_fold = split.development_fold[participant]
        expected_train = split.inner_train(expected_fold)
        if (
            row["source_model_role"] != "development_oof"
            or row["generator_fit_mode"] != "oof-refit"
            or row["held_out_fold"] != expected_fold
        ):
            raise RFTContractError("development candidate was not generated by its OOF model")
    elif participant in split.selection_validation:
        expected_train = split.development_train
        if (
            row["source_model_role"] != "development_provisional"
            or row["generator_fit_mode"] != "provisional"
            or row["held_out_fold"] is not None
        ):
            raise RFTContractError("selection candidate must come from development provisional model")
    else:
        raise RFTContractError("RFT participant is outside the outer-train method split")
    if participant in expected_train:
        raise RFTContractError("candidate generator trained on its target participant")
    if row["generator_train_participants_sha256"] != participant_set_sha256(expected_train):
        raise RFTContractError("generator training participant provenance mismatch")


def character_f_score(candidate: str, reference: str, *, max_order: int = 6, beta: float = 2.0) -> float:
    """Dependency-free chrF-style character n-gram F score on a 0-100 scale."""
    if not isinstance(candidate, str) or not isinstance(reference, str) or max_order <= 0 or beta <= 0:
        raise RFTContractError("invalid chrF inputs")
    candidate = "".join(candidate.split())
    reference = "".join(reference.split())
    if not candidate or not reference:
        return 0.0
    precisions = []
    recalls = []
    usable_orders = min(max_order, len(candidate), len(reference))
    for order in range(1, usable_orders + 1):
        def grams(text: str) -> Counter[str]:
            return Counter(text[i:i + order] for i in range(max(0, len(text) - order + 1)))
        left = grams(candidate)
        right = grams(reference)
        overlap = sum((left & right).values())
        precisions.append(overlap / max(1, sum(left.values())))
        recalls.append(overlap / max(1, sum(right.values())))
    precision = sum(precisions) / len(precisions)
    recall = sum(recalls) / len(recalls)
    if precision == 0 and recall == 0:
        return 0.0
    beta2 = beta * beta
    return 100.0 * (1 + beta2) * precision * recall / (beta2 * precision + recall)


def _minmax(value: float, values: list[float]) -> float:
    low = min(values)
    high = max(values)
    return 0.5 if high == low else (value - low) / (high - low)


def score_and_select_rft_candidates(
    rows: Iterable[Mapping[str, Any]],
    split: NestedSelectionSplit,
    *,
    acceptance_quantile: float = 0.75,
    minimum_pool_size: int = 20,
    bge_weight: float = 0.5,
    chrf_weight: float = 0.2,
    consistency_weight: float = 0.3,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    candidates = [dict(row) for row in rows]
    if not candidates:
        raise RFTContractError("RFT candidates cannot be empty")
    if abs(bge_weight + chrf_weight + consistency_weight - 1.0) > 1e-9:
        raise RFTContractError("RFT reward weights must sum to one")
    if not 0 < acceptance_quantile < 1 or minimum_pool_size <= 0:
        raise RFTContractError("invalid RFT selection settings")
    for row in candidates:
        validate_oof_candidate(row, split)
        row["chrf"] = character_f_score(row["candidate_text"], row["gold_text"])
        failure, reasons = candidate_failure(Candidate(
            tuple(row["state_context"]), row["candidate_text"], 0.0, 0.0,
            float(row["consistency"]), bool(row["forced_stop"]),
            f"{row['record_id']}:{row['candidate_index']}",
        ))
        row["failure_penalty"] = failure
        row["failure_reasons"] = list(reasons)
    by_fold_question: dict[tuple[object, str], list[dict[str, Any]]] = defaultdict(list)
    by_fold: dict[object, list[dict[str, Any]]] = defaultdict(list)
    for row in candidates:
        fold_key = row["held_out_fold"] if row["held_out_fold"] is not None else "selection"
        by_fold_question[(fold_key, row["question_id"])].append(row)
        by_fold[fold_key].append(row)
    for row in candidates:
        fold_key = row["held_out_fold"] if row["held_out_fold"] is not None else "selection"
        local = by_fold_question[(fold_key, row["question_id"])]
        pool = local if len(local) >= minimum_pool_size else by_fold[fold_key]
        bge_values = [float(item["bge_similarity"]) for item in pool]
        chrf_values = [float(item["chrf"]) for item in pool]
        consistency_values = [float(item["consistency"]) for item in pool]
        row["reward"] = (
            bge_weight * _minmax(float(row["bge_similarity"]), bge_values)
            + chrf_weight * _minmax(float(row["chrf"]), chrf_values)
            + consistency_weight * _minmax(float(row["consistency"]), consistency_values)
            - float(row["failure_penalty"])
        )
        row["reward_pool"] = (
            f"{fold_key}:{row['question_id']}" if pool is local else f"{fold_key}:ALL_Q1_Q6"
        )
    pool_rewards: dict[str, list[float]] = defaultdict(list)
    fold_bge: dict[object, list[float]] = defaultdict(list)
    baselines: dict[str, float] = {}
    by_record: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in candidates:
        pool_rewards[row["reward_pool"]].append(float(row["reward"]))
        fold_key = row["held_out_fold"] if row["held_out_fold"] is not None else "selection"
        fold_bge[fold_key].append(float(row["bge_similarity"]))
        by_record[row["record_id"]].append(row)
        if row["candidate_index"] == 0:
            if row["record_id"] in baselines:
                raise RFTContractError("record has duplicate first-seed baseline")
            baselines[row["record_id"]] = float(row["reward"])
    if set(baselines) != set(by_record):
        raise RFTContractError("each RFT record requires candidate_index=0 baseline")
    accepted: list[dict[str, Any]] = []
    for record_id, record_rows in sorted(by_record.items()):
        best = max(record_rows, key=lambda row: (row["reward"], -row["candidate_index"]))
        fold_key = best["held_out_fold"] if best["held_out_fold"] is not None else "selection"
        threshold = _quantile(pool_rewards[best["reward_pool"]], acceptance_quantile)
        bge_median = _quantile(fold_bge[fold_key], 0.5)
        if (
            not best["failure_reasons"]
            and float(best["reward"]) >= threshold
            and float(best["reward"]) > baselines[record_id]
            and float(best["bge_similarity"]) >= bge_median
        ):
            accepted.append(best)
    coverage = len(accepted) / len(by_record)
    role_records = Counter(row["source_model_role"] for row in candidates)
    role_records = {
        role: len({row["record_id"] for row in candidates if row["source_model_role"] == role})
        for role in role_records
    }
    role_accepted = Counter(row["source_model_role"] for row in accepted)
    coverage_by_role = {
        role: role_accepted.get(role, 0) / count
        for role, count in sorted(role_records.items())
    }
    return accepted, {
        "eligible_records": len(by_record),
        "accepted_records": len(accepted),
        "coverage": coverage,
        "eligible_records_by_role": dict(sorted(role_records.items())),
        "accepted_records_by_role": dict(sorted(role_accepted.items())),
        "coverage_by_role": coverage_by_role,
        "q7_gold_used": False,
        "maximum_one_candidate_per_record": len({row["record_id"] for row in accepted}) == len(accepted),
    }


def _quantile(values: list[float], probability: float) -> float:
    ordered = sorted(values)
    position = probability * (len(ordered) - 1)
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    fraction = position - lower
    return ordered[lower] * (1 - fraction) + ordered[upper] * fraction


def rft_selection_gate(
    *,
    bge_delta: float,
    chrf_delta: float,
    consistency_delta: float,
    repetition_delta: float,
    template_leak_delta: float,
    coverage: float,
    minimum_coverage: float = 0.2,
    bge_min_delta: float = 0.0,
    chrf_min_delta: float = -0.5,
    consistency_min_delta: float = 0.0,
    failure_max_delta: float = 0.0,
) -> tuple[bool, dict[str, bool]]:
    checks = {
        "bge_non_degradation": bge_delta >= bge_min_delta,
        "chrf_non_degradation": chrf_delta >= chrf_min_delta,
        "consistency_improvement": consistency_delta > consistency_min_delta,
        "repetition_non_degradation": repetition_delta <= failure_max_delta,
        "template_leak_non_degradation": template_leak_delta <= failure_max_delta,
        "coverage": coverage >= minimum_coverage,
    }
    return all(checks.values()), checks


def build_rft_training_rows(
    gold_rows: Iterable[Mapping[str, Any]],
    accepted: Iterable[Mapping[str, Any]],
) -> list[dict[str, Any]]:
    """Build a deterministic 2:1 gold:pseudo continuation dataset."""
    gold = [dict(row) for row in gold_rows]
    accepted_rows = [dict(row) for row in accepted]
    accepted_by_record = {row["record_id"]: row for row in accepted_rows}
    if len(accepted_by_record) != len(accepted_rows):
        raise RFTContractError("accepted records must be unique")
    gold_by_record: dict[str, dict[str, Any]] = {}
    for row in gold:
        metadata = row.get("metadata")
        record_id = metadata.get("record_id") if isinstance(metadata, dict) else None
        if not isinstance(record_id, str) or not record_id or record_id in gold_by_record:
            raise RFTContractError("gold Realizer records must have unique record IDs")
        gold_by_record[record_id] = row
    if not accepted_by_record:
        raise RFTContractError("RFT requires at least one accepted pseudo target")
    if not set(accepted_by_record) <= set(gold_by_record):
        raise RFTContractError("accepted RFT record is absent from gold Realizer rows")
    result: list[dict[str, Any]] = []
    for record_id in sorted(accepted_by_record):
        row = gold_by_record[record_id]
        result.extend([{**row, "rft_target_source": "gold"} for _ in range(2)])
        pseudo = dict(row)
        pseudo["target_text"] = accepted_by_record[record_id]["candidate_text"]
        pseudo["rft_target_source"] = "oof_pseudo"
        result.append(pseudo)
    return result
